#: 预转成 ndarray（每个预设只做一次 interp，别在生成循环里反复转 tuple）。
_PROFILE_R = {
    key: np.asarray(val["r4"], dtype=np.float64) / 4.0 for key, val in _PROFILES.items()
}
_PROFILE_A = {
    key: np.asarray(val["a2"], dtype=np.float64) / 2.0 for key, val in _PROFILES.items()
}
_PROFILE_KEYS = tuple(sorted(_PROFILES))

#: 圆度下限：PS 允许 Rndn=0（线状笔尖）；除零保护与 `convert._circle_mask` 同口径。
_MIN_ROUNDNESS_RATIO = 1e-3

#: 生成位图外围强制归零的环宽（px）：α=0 的尾巴 + 反相后恰好让「边框 255」成立。
_BORDER_PX = 1.0


@dataclass(frozen=True)
class GeneratedTip:
    """一次生成的采样笔尖。

    mask：   (edge, edge) uint8，**项目既有 mask 约定（255=墨）**，用于预览与自检；
    stored： (edge, edge) uint8，**255 − mask**，直接写 L 模式 PNG 给 Krita（深=墨）；
    edge：   位图边长 = Krita 尺寸字段（scale=1 时）；
    spacing_basis：PS 100% 间距基准 / Krita 基准 = Dmtr × 短/长 ÷ edge。
    """

    mask: np.ndarray
    stored: np.ndarray
    edge: int
    hardness: float
    footprint_ratio: float
    spacing_basis: float


def _clamp_hardness(hardness: float | None) -> float:
    """Hrdn → [0,100]。缺省（None）取 50：与旧 auto_brush 的 fade=0.5 默认一致。"""
    if hardness is None:
        return 50.0
    return max(0.0, min(100.0, float(hardness)))


def _alpha_of(key: float, radius: np.ndarray) -> np.ndarray:
    """单档剖面：像素半径 → α（超出采样尾部按 0）。"""
    return np.interp(radius, _PROFILE_R[key], _PROFILE_A[key],
                     left=float(_PROFILE_A[key][0]), right=0.0)


def footprint_ratio(hardness: float | None) -> float:
    """α=0 半径 / 标称半径（130 实测 1.44 / 1.24 / 1.01，中间硬度线性内插）。"""
    h = _clamp_hardness(hardness)
    hs = list(_PROFILE_KEYS)
    rs = [_PROFILES[k]["r_vis"] / _CALIBRATION_RADIUS for k in hs]
    return float(np.interp(h, hs, rs))


def alpha_at(radius_px: np.ndarray, hardness: float | None) -> np.ndarray:
    """给定硬度的径向 α 剖面（0..255 浮点）。

    三档之间：在同一像素半径上对 α 线性内插（不是对半径内插 —— 三档的软边宽度不同，
    只有「同半径同 α 权重」才让两端的修法在中间硬度上连续）。
    """
    r = np.asarray(radius_px, dtype=np.float64)
    h = _clamp_hardness(hardness)
    keys = list(_PROFILE_KEYS)
    if h <= keys[0]:
        return _alpha_of(keys[0], r)
    if h >= keys[-1]:
        return _alpha_of(keys[-1], r)
    for lo, hi in zip(keys, keys[1:]):
        if lo <= h <= hi:
            w = (h - lo) / (hi - lo)
            return (1.0 - w) * _alpha_of(lo, r) + w * _alpha_of(hi, r)
    raise AssertionError("硬度内插区间未命中：%r" % (h,))  # 理论上不可达


def tip_edge(hardness: float | None, diameter: float) -> int:
    """位图边长 L = 2·ceil(r_vis)+2（130 §1.3 公式；h0/50/100@Dmtr=200 → 290/250/204）。"""
    d = max(1.0, float(diameter))
    half_footprint = footprint_ratio(hardness) * (d / 2.0)
    return int(2 * math.ceil(half_footprint) + 2)


def spacing_basis(hardness: float | None, diameter: float, roundness: float = 100.0,
                  edge: int | None = None) -> float:
    """计算笔刷改采样后要乘回 spacing 的基准比 = (Dmtr × 短/长) / 位图边长。

    PS 对**计算笔刷**的 100% 间距基准 = 标称直径（131 表 3：b_PS = 200.00 = Dmtr，
    10/50/100% 三档）→ 椭圆笔尖的短边基准 = Dmtr × Rndn/100（与采样笔尖的
    「蒙版短边」同一条规则）。改采样后 Krita 的间距基准变成**位图边长**（=PS 足印，
    h0 时 1.45×Dmtr），不乘回这个比值，步长会整体放大到 1.45× —— 那是换算基准变了，
    不是「手感校准系数」。
    """
    d = max(1.0, float(diameter))
    ratio = max(_MIN_ROUNDNESS_RATIO, min(1.0, float(roundness) / 100.0))
    if edge is None:
        edge = tip_edge(hardness, d)
    return (d * ratio) / float(edge)


def build_tip(hardness: float | None, diameter: float,
              roundness: float = 100.0) -> GeneratedTip:
    """按 PS 剖面生成正方形采样笔尖（mask=255 墨 / stored=255−mask）。

    - 位图边长 = 2·ceil(r_vis)+2（偶数；四周各留 1px 的 α=0 环 → 反相后边框整圈 255）；
    - 圆度 <100 时按「先把剖面沿短轴压缩」生成椭圆（与旧 auto_brush 的 ratio 同轴序），
      长轴足印仍由 Hrdn 的 r_vis 决定；
    - 正方形 + 边框 255 是**结构性质**，由径向剖面 + 强制外环归零自然满足，
      不经过 `_square_tip`（铁律 17：补平方保持原样）。
    """
    d = max(1.0, float(diameter))
    h = _clamp_hardness(hardness)
    ratio = max(_MIN_ROUNDNESS_RATIO, min(1.0, float(roundness) / 100.0))
    edge = tip_edge(h, d)
    center = (edge - 1) / 2.0
    yy, xx = np.mgrid[0:edge, 0:edge].astype(np.float64)
    dx = xx - center
    dy = (yy - center) / ratio
    # 位图 1px = PS 实际 1px（足印保真），而剖面表是在标定直径 200 上采的：
    # 剖面按「归一化半径 u=r/R」缩放，所以查表半径 = 位图半径 × (标定R / 目标R)。
    # 即 200px 直径时系数为 1（与 130 位图逐字节一致），400px 时剖面被放大 2 倍。
    radius_px = np.hypot(dx, dy)
    radius_cal = radius_px * (_CALIBRATION_RADIUS / (d / 2.0))
    alpha = alpha_at(radius_cal, h)
    # 外环归零按**位图半径**判（不是查表半径），保证任意直径下边框整圈 255。
    alpha = np.where(radius_px >= (edge / 2.0) - _BORDER_PX, 0.0, alpha)
    # 先反相再取整：α 是半步长（uint8 中位数），np.rint 的「银行家舍入」在
    # 255−α 与 α 两侧会给出不同的 ±1，只有按 130 的写法（rint(255−α)）才能
    # 逐字节复现实验位图。mask 由 stored 反推，保证预览与内嵌字节是同一组像素。
    stored = np.clip(np.rint(255.0 - alpha), 0, 255).astype(np.uint8)
    mask = (255 - stored).astype(np.uint8)
    return GeneratedTip(mask=mask, stored=stored, edge=edge, hardness=h,
                        footprint_ratio=footprint_ratio(h),
                        spacing_basis=spacing_basis(h, d, roundness, edge))


def verify_generated_tip(tip: GeneratedTip) -> dict:
    """生成后自检（130 `verify_tip` 口径）：正方形 + 外圈整圈 255。

    失败抛 ValueError（宁可转换失败，也不要静默产出补集/带透明边框的位图）。
    """
    stored = tip.stored
    if stored.ndim != 2:
        raise ValueError("生成的笔尖必须是二维数组：shape=%r" % (stored.shape,))
    h, w = stored.shape
    if h != w:
        raise ValueError("生成的笔尖必须是正方形：%dx%d" % (w, h))
    border = np.concatenate([stored[0, :], stored[-1, :], stored[:, 0], stored[:, -1]])
    if not bool(np.all(border == 255)):
        raise ValueError("生成的笔尖外圈必须整圈 255（反相约定：255=透明）：min=%d"
                         % int(border.min()))
    return {"shape": [int(h), int(w)], "edge": tip.edge, "square": True,
            "border_value": 255, "border_uniform": True,
            "hardness": tip.hardness, "footprint_ratio": tip.footprint_ratio,
            "spacing_basis": tip.spacing_basis}


