"""按 Photoshop 硬度（Hrdn）径向剖面生成采样笔尖位图（v1.5.0 · 任务 133）。

## 为什么要有这条路径（证据链）

任务 130（`docs/工作流程/130-实验-硬度剖面.md`、工具 `tools/exp_hardness_profile.py`）的定论：

1. **PS 的 Hrdn 语义 = 「软边伸出标称半径之外」**，不是「在半径 R 内把剖面压软」：
   α=0 的半径 ≈ 1.44 / 1.24 / 1.01 × R（h=0/50/100，R = Dmtr/2）；
2. **Krita 的 auto_brush 复刻不了**：hfade/vfade 只作用于 1.00R 以内，实测过渡带
   h0 −15.60px/−19.81%、h50 +7.33px/+22.63%（130 表 A）；
3. **把 PS 径向剖面烘成正方形采样笔尖 + png_brush 可以复刻**，但**硬前置**是
   Krita 尺寸字段（= 位图边长）必须取 **PS 实际足印**：h0/50/100 → 290/250/204 px
   （=标称 200 的 1.45/1.25/1.02×）。改后 10–90% 过渡带：h0 −0.90px/−1.14%、
   h50 +0.04px/+0.12%、h100 +0.50px（130 表 B）；若尺寸仍写 200（B200 变体）
   立刻退回 h0 −24.55px、h50 −6.32px ⇒ 不可行。

## 极性（130 §三实测，别改）

Krita 5.3.3 对 L 模式 png_brush 的解释是 **深（小字节值）= 墨、白（255）= 透明**
（全白位图渲染 alpha=0、全黑位图满墨；逐半径满足 `α_渲染 + 位图灰度 = 255`）。
所以本模块生成的位图写 **255 − α**：墨芯接近 0、外围（α=0）恰为 255 —— 任务书要求的
「正方形 + 边框 255」因此**字面成立**，且**不需要、也不触发** `convert._square_tip` 的补白
（铁律 17：补平方不许动）。

## 数据来源与精确性

剖面来自入库 PS 真值 `docs/数据/偏差/ps/hardness__computed__v{0,50,100}.png`
（130 按质心做 0.5px 径向 α 中位数采样、强制单调不增，落盘 `.tmp/130/ps_profiles.json`）。
本模块把它固化成整数表，保证**逐字节**复现 130 的内嵌 PNG：

- `r4` = round(4 × r)：0.25px 网格，精确还原采样半径（前几环因像素数 <8 有缺环，是非均匀网格）；
- `a2` = round(2 × α)：PS 真值是 uint8 的中位数，必为整数或半步长。

三档位图与 130 记录的 sha256 逐字节一致（`tests/test_hardness_tip_v150.py` 钉死）：
h0 f4f98b81…、h50 042b1c6f…、h100 cf5d2fb7…。

### 直径缩放（133 首件补测，PS 9 组 + Krita 9 组）

剖面按「归一化半径 u = r/R」定义，所以查表半径 = 位图半径 × (标定R / 目标R) = 位图半径 × 200/Dmtr。
3 档 h × 3 个直径（100/200/400）实测的归一化过渡带（px/R）：

| h | D=100 | D=200 | D=400 | 判读 |
|---|---|---|---|---|
| 0 | 0.78750 | 0.78708 | 0.78750 | 差 **0.05%**，缩放成立 |
| 50 | 0.33212 | 0.32358 | 0.31917 | 差 ≤**4%**（绝对 ≤1px），缩放可接受 |
| 100 | 0.03767 | 0.01899 | 0.00985 | **不缩放**：PS 过渡带是 AA 绝对带宽 1.88/1.90/1.97px |

h=100 的例外意味着：按比例放大后在大直径会多估 (D/200)×1.9 − 1.9 px（D≳415 起
超过 2px 绝对差判据）。本轮不改模型（没有 ≤415px 的反例，且改它需要 PS 侧
h≥100 的更多半径证据），已写进 133 报告「遗留」。

## 中间硬度怎么办（插值假设，已登记未量测）

0/50/100 三档之间按「**同一像素半径上对 α 做分段线性内插**」处理，足印半径
`r_vis / R` 同样线性内插。130 F-8 只量了 3 档（且只有 Dmtr=200 一个半径），
所以「剖面随直径等比缩放」与「中间硬度线性内插」两条是**假设**，不是已验证结论：
132 §4.5 的 R 项（半径缩放不变性）与 133 报告的「未量测」清单已登记。
"""

